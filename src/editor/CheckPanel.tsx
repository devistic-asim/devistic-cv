import { Badge } from '../components/ui'
import { scoreCv, type Check } from '../lib/score'
import type { CVDocument } from '../lib/types'

export function CheckPanel({
  doc,
  onJump,
}: {
  doc: CVDocument
  onJump: (section: string) => void
}) {
  const result = scoreCv(doc)
  const groups: { tone: Check['severity']; label: string }[] = [
    { tone: 'error', label: 'Fix' },
    { tone: 'warn', label: 'Improve' },
    { tone: 'info', label: 'Consider' },
    { tone: 'pass', label: 'In good shape' },
  ]
  return (
    <div className="grid gap-4" data-tour="check">
      <div className="flex items-center gap-4">
        <ScoreRing score={result.score} />
        <div>
          <h2 className="font-serif text-xl">Checklist</h2>
          <p className="text-sm text-muted">A fixed set of rules. Nothing here is generated by a model.</p>
        </div>
      </div>
      {groups.map((group) => {
        const items = result.checks.filter((check) => check.severity === group.tone)
        if (!items.length) return null
        return (
          <section key={group.tone}>
            <h3 className="mb-2 text-sm font-semibold">{group.label}</h3>
            <ul className="grid gap-2">
              {items.map((check) => (
                <li key={check.id}>
                  <button type="button" onClick={() => onJump(check.section === 'design' ? 'design' : check.section || 'outline')} className="w-full rounded-md border border-line bg-surface px-3 py-2 text-left hover:bg-sunken">
                    <span className="flex items-center justify-between gap-2">
                      <span className="font-semibold">{check.title}</span>
                      <Badge tone={check.severity === 'pass' ? 'good' : check.severity === 'error' || check.severity === 'warn' ? 'warn' : 'highlight'}>
                        {check.severity}
                      </Badge>
                    </span>
                    <span className="mt-1 block text-xs leading-relaxed text-muted">{check.detail}</span>
                  </button>
                </li>
              ))}
            </ul>
          </section>
        )
      })}
    </div>
  )
}

function ScoreRing({ score }: { score: number }) {
  const tone = score >= 80 ? 'Strong' : score >= 60 ? 'Usable' : 'Needs work'
  return (
    <div className="grid h-20 w-20 place-items-center rounded-full border-4 border-primary text-center" aria-label={`Score ${score} out of 100, ${tone}`}>
      <span>
        <span className="block text-xl font-semibold leading-none">{score}</span>
        <span className="text-[10px] font-semibold uppercase tracking-wide text-muted">{tone}</span>
      </span>
    </div>
  )
}
